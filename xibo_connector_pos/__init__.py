def _ensure_columns(cr, table, columns):
    """Add any missing column to ``table``. Idempotent."""
    cr.execute(
        "SELECT 1 FROM information_schema.tables WHERE table_name = %s",
        (table,),
    )
    if not cr.fetchone():
        _logger.info("[XIBO POS PRE-INIT] table %s not found yet; skipping", table)
        return

    cr.execute(
        "SELECT column_name FROM information_schema.columns "
        "WHERE table_name = %s",
        (table,),
    )
    existing = {row[0] for row in cr.fetchall()}

    added = 0
    for name, pg_type, comment in columns:
        if name in existing:
            continue
        try:
            cr.execute(
                'ALTER TABLE "%s" ADD COLUMN IF NOT EXISTS "%s" %s'
                % (table, name, pg_type)
            )
            added += 1
            _logger.info(
                "[XIBO POS PRE-INIT] added column %s.%s (%s)",
                table, name, pg_type,
            )
        except Exception as e:
            # Don't crash the upgrade. Log it and let Odoo's own machinery
            # try again on the next pass.
            _logger.warning(
                "[XIBO POS PRE-INIT] could not add %s.%s: %s",
                table, name, e,
            )
    if added:
        _logger.info(
            "[XIBO POS PRE-INIT] %s: added %s column(s) defensively",
            table, added,
        )


def pre_init_check_schema(env_or_cr):
    """Pre-init hook entrypoint. Defensive schema validation.

    Called by Odoo before this module's normal install/upgrade routine.
    Accepts either an Environment (Odoo 17+) or a cursor (older Odoo) — we
    detect at runtime and adapt.
    """
    # Odoo 17+ passes ``env``; older versions pass ``cr``.
    cr = getattr(env_or_cr, 'cr', env_or_cr)
    try:
        _logger.info("[XIBO POS PRE-INIT] checking schema consistency...")
        _ensure_columns(cr, 'pos_order', _POS_ORDER_COLUMNS)
        _ensure_columns(cr, 'pos_config', _POS_CONFIG_COLUMNS)
        _logger.info("[XIBO POS PRE-INIT] schema check complete")
    except Exception as e:
        # Even if everything fails, never break the upgrade.
        _logger.exception(
            "[XIBO POS PRE-INIT] hook failed (non-fatal, upgrade continues): %s",
            e,
        )
