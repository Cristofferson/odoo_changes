_logger = logging.getLogger(__name__)


# =============================================================================
# Pre-init hook: defensive schema validation
# =============================================================================
#
# When this module is upgraded in-place (the customer drops new files into the
# addons folder and restarts Odoo, without going through "Apps -> Upgrade"),
# Odoo loads the new Python code but does NOT run schema migrations. This
# leaves an inconsistent state: the model declares new fields, but the
# physical columns do not exist on the table. Any read of those fields then
# raises ``psycopg2.errors.UndefinedColumn`` in the user's face.
#
# We close that window here. ``pre_init_hook`` runs before Odoo's normal
# table-creation step on install/upgrade, and is the perfect place to ensure
# every column declared on the latest version exists on disk — even if Odoo's
# own upgrade machinery didn't catch the version bump.
#
# All ALTER TABLE statements use ``IF NOT EXISTS`` so re-running the hook is
# always safe (idempotent). The hook never blocks on errors: if a single
# column can't be added it logs and moves on, leaving Odoo's normal upgrade
# path to finish the job.
# =============================================================================

